const DICTS = { en, hi, mr, ta, te, bn };

const LangCtx = createContext(null);

export function LanguageProvider({ children }) {
  const [lang, setLangState] = useState(localStorage.getItem("lang") || "en");
  const setLang = (l) => {
    setLangState(l);
    localStorage.setItem("lang", l);
    document.documentElement.lang = l;
  };
  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);

  const t = (k) => DICTS[lang]?.[k] ?? en[k] ?? k;

  const tr = (text) => {
    if (!text || lang === "en") return text;
    const key = String(text).trim().toLowerCase();
    return PHRASES[key]?.[lang] ?? text;
  };

  const tService = (name) => {
    if (!name) return "";
    const key = String(name).trim().toLowerCase();
    return SERVICE_NAMES[key]?.[lang] ?? name;
  };

  const tServiceDesc = (name, fallback = "") => {
    if (lang === "en") return fallback;
    const key = String(name || "").trim().toLowerCase();
    return SERVICE_DESCS[key]?.[lang] ?? tr(fallback);
  };

  return (
    <LangCtx.Provider value={{ lang, setLang, t, tr, tService, tServiceDesc, LANGUAGES }}>
      {children}
    </LangCtx.Provider>
  );
}

export const useLang = () => useContext(LangCtx);
