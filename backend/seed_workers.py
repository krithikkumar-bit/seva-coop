def seed_workers():
    db = database.SessionLocal()
    try:
        created_count = 0
        for w in WORKERS_DATA:
            existing_user = db.query(models.User).filter(
                (models.User.phone == w["phone"]) | (models.User.email == w["email"])
            ).first()

            if not existing_user:
                user = models.User(
                    full_name=w["name"],
                    phone=w["phone"],
                    email=w["email"],
                    password_hash=hash_password(secrets.token_urlsafe(24)),
                    role="worker",
                    language="en"
                )
                db.add(user)
                db.commit()
                db.refresh(user)
            else:
                user = existing_user

            # Check profile
            profile = db.query(models.WorkerProfile).filter_by(user_id=user.id).first()
            if not profile:
                profile = models.WorkerProfile(
                    user_id=user.id,
                    skills=w["skills"],
                    experience_years=w["experience"],
                    hourly_rate=w["rate"],
                    bio=w["bio"],
                    address=w["address"],
                    lat=w["lat"],
                    lng=w["lng"],
                    availability="available",
                    verification_status="verified",
                    id_proof_no=w["id_proof"],
                    rating_sum=w["rating_sum"],
                    rating_count=w["rating_count"],
                    jobs_done=w["jobs_done"]
                )
                db.add(profile)
                created_count += 1
            else:
                # Update verification status and fields if needed
                profile.verification_status = "verified"
                profile.skills = w["skills"]
                profile.availability = "available"

        db.commit()
        print(f"Successfully processed {len(WORKERS_DATA)} workers. Created {created_count} new worker profiles.")
    finally:
        db.close()

if __name__ == "__main__":
    seed_workers()
